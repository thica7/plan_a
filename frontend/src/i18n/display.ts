export function displayLabel(value: string, locale: Locale): string {
  return labels[value]?.[locale === "zh-CN" ? 0 : 1] ?? value;
}

export function displayScope(value: string, locale: Locale): string {
  const [dimension, ...product] = value.split("::");
  return product.length ? `${displayLabel(dimension, locale)} / ${product.join("::")}` : displayLabel(value, locale);
}

